  var REVIEWER_COLORS = { dima: '#e5484d', deni: '#f5a524', yura: '#38bdf8', ihor: '#a78bfa' };

  function t(key, params) {
    var lang = ((window.MB.store && window.MB.store.state && window.MB.store.state.lang)) || document.documentElement.lang || 'uk';
    var dict = STR[lang] || STR.uk;
    var s = dict[key] != null ? dict[key] : (STR.uk[key] != null ? STR.uk[key] : key);
    if (params) {
      Object.keys(params).forEach(function (k) {
        s = s.split('{' + k + '}').join(String(params[k]));
      });
    }
    return s;
  }

  /* Slavic plural: forms = ['фільм','фільми','фільмів'] or ['movie','movies'] */
  function plural(n, forms) {
    if (forms.length === 2) return n === 1 ? forms[0] : forms[1];
    var m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return forms[0];
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1];
    return forms[2];
  }

  function moviesCount(n) {
    var lang = ((window.MB.store && window.MB.store.state && window.MB.store.state.lang)) || 'uk';
    if (lang === 'uk') return n + ' ' + plural(n, ['фільм', 'фільми', 'фільмів']);
    return n + ' ' + plural(n, ['movie', 'movies']);
  }
  function ratingsCount(n) {
    var lang = ((window.MB.store && window.MB.store.state && window.MB.store.state.lang)) || 'uk';
    if (lang === 'uk') return n + ' ' + plural(n, ['оцінка', 'оцінки', 'оцінок']);
    return n + ' ' + plural(n, ['rating', 'ratings']);
  }

  window.MB.t = t;
  window.MB.plural = plural;
  window.MB.moviesCount = moviesCount;
  window.MB.ratingsCount = ratingsCount;
  window.MB.REVIEWER_COLORS = REVIEWER_COLORS;
